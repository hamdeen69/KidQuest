export function getRandomKidQuote(excludeIndex?: number): {
  quote: string;
  index: number;
} {
  const total = KIDS_ENCOURAGING_QUOTES.length;
  if (total === 0) {
    return { quote: 'วันนี้หนูเก่งมาก! มาทำภารกิจสนุกๆ กันเถอะ', index: 0 };
  }
  let idx = Math.floor(Math.random() * total);
  if (total > 1 && idx === excludeIndex) {
    idx = (idx + 1) % total;
  }
  return {
    quote: KIDS_ENCOURAGING_QUOTES[idx],
    index: idx,
  };
}
